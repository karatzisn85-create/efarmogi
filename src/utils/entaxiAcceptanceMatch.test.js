/**
 * @jest-environment node
 */
const match = require('../../app/core/entaxiAcceptanceMatch');

const ENTAXI = {
  subject: 'Τροποποίηση της Πράξης «ΑΝΑΒΑΘΜΙΣΗ ΠΡΑΣΙΝΟΥ ΣΕ ΚΟΙΝΟΧΡΗΣΤΟΥΣ ΧΩΡΟΥΣ ΤΟΥ Δ. ΑΡΧΑΝΩΝ ΑΣΤΕΡΟΥΣΙΩΝ» με Κωδικό ΟΠΣ 5225036',
  opsCode: '5225036',
  documentDate: '2025-10-15',
};

describe('entaxiAcceptanceMatch', () => {
  it('βαθμολογεί την απόφαση Δ.Σ. του παραδείγματος πάνω από άσχετες της ίδιας μέρας', () => {
    const ranked = match.rankAcceptanceCandidates(ENTAXI, [
      {
        ada: 'ΨΤ0ΨΩΨΜ-Γ33',
        subject: '240/2025 απόφαση Δημοτικού Συμβουλίου :Έγκριση απευθείας αγοράς ακινήτου',
        issueDate: '2025-11-18',
      },
      {
        ada: '624ΙΩΨΜ-Ζ12',
        subject: '230/2025 απόφαση Δημοτικού Συμβουλίου :Τροποποίηση προϋπολογισμού οικονομικού έτους 2025 Δήμου Αρχανών Αστερουσίων για την εκτέλεση του 1ου υποέργου του χρηματοδοτούμενου έργου «Αναβάθμιση πρασίνου σε κοινόχρηστους του Δ. Αρχανών Αστερουσίων »',
        issueDate: '2025-11-18',
      },
      {
        ada: '6ΞΧΜΩΨΜ-ΚΟΟ',
        subject: 'Απόφαση Δημοτικής Επιτροπής (360/2025): "Αποδοχή μεταβολής χρηματοδότησης υποέργων του έργου αναβάθμιση πρασίνου σε κοινόχρηστους χώρους του δ. Αρχανών Αστερουσίων και εισήγηση για τροποποίηση προϋπολογισμού"',
        issueDate: '2025-11-18',
      },
    ]);
    expect(ranked.map((r) => r.ada)).toEqual(['624ΙΩΨΜ-Ζ12', '6ΞΧΜΩΨΜ-ΚΟΟ']);
    expect(ranked[0].role).toBe('council_budget');
    expect(ranked[1].role).toBe('committee_accept');
  });

  it('δεν κρατά πληρωμή που απλώς αναφέρει τον ΟΠΣ', () => {
    const ranked = match.rankAcceptanceCandidates(ENTAXI, [{
      ada: '6ΖΙΓΩΨΜ-ΦΘ5',
      subject: 'Χρηματοδότηση ΠΔΕ για: εργασίες κλαδοκοπών δένδρων (κωδικό ΟΠΣ (MIS) 5225036)- ΛΟΓΙΣΤΙΚΗΣ ΤΑΚΤΟΠΟΙΗΣΗΣ',
      issueDate: '2025-06-11',
    }]);
    expect(ranked).toEqual([]);
  });

  it('δεν κρατά απόφαση πριν την ημερομηνία ένταξης χωρίς ρόλο αποδοχής', () => {
    const ranked = match.rankAcceptanceCandidates(ENTAXI, [{
      ada: '9ΒΜΠΩΨΜ-ΤΕΦ',
      subject: '60/2025 απόφαση Δημοτικού Συμβουλίου :Έγκριση τεχνικού προγράμματος έτους 2025',
      issueDate: '2025-04-22',
    }]);
    expect(ranked).toEqual([]);
  });

  it('κρατά την υποψήφια αποδοχή του σεναρίου ασυσχέτιστης ένταξης', () => {
    const ranked = match.rankAcceptanceCandidates({
      subject: 'Μεμονωμένη ένταξη',
      opsCode: '5225999',
      documentDate: '2025-10-01',
    }, [{
      ada: '624ΙΩΨΜ-Ζ12',
      subject: '230/2025 απόφαση Δημοτικού Συμβουλίου :Τροποποίηση προϋπολογισμού οικονομικού έτους 2025 για την εκτέλεση του χρηματοδοτούμενου έργου «Μεμονωμένη ένταξη» ΟΠΣ 5225999',
      issueDate: '2025-11-18',
    }]);
    expect(ranked).toHaveLength(1);
    expect(ranked[0].role).toBe('council_budget');
  });

  it('χτίζει φράσεις αναζήτησης από ΟΠΣ και τίτλο', () => {
    const phrases = match.buildSearchPhrases(ENTAXI);
    expect(phrases).toContain('5225036');
    expect(phrases.some((p) => /ΑΝΑΒΑΘΜΙΣΗ/i.test(p) && /ΠΡΑΣΙΝΟΥ/i.test(p))).toBe(true);
  });

  it('σε έλεγχο τροποποίησης κρατά αποδοχή τροποποίησης και Δ.Σ. για υλοποίηση πράξης', () => {
    const ranked = match.rankAcceptanceCandidates({
      subject: 'Ένταξη της Πράξης «ΒΕΛΤΙΩΣΗ ΚΑΙ ΣΥΝΤΗΡΗΣΗ ΔΡΟΜΩΝ ΜΕΛΙΔΟΧΩΡΙΟΥ» με Κωδικό ΟΠΣ 5221312',
      opsCode: '5221312',
      documentDate: '2024-01-25',
    }, [
      {
        ada: 'ΨΓ25ΩΨΜ-ΘΓ4',
        subject: 'Απόφαση Δημοτικής Επιτροπής (299/2025): "Αποδοχή τροποποίησης πράξης: «βελτίωση και συντήρηση δρόμων Μελιδοχωρίου» και εισήγηση για τροποποίηση προϋπολογισμού"',
        issueDate: '2025-10-07',
      },
      {
        ada: 'Ψ1ΘΟΩΨΜ-ΧΨΓ',
        subject: '195/2025 απόφαση Δημοτικού Συμβουλίου :Τροποποίηση προϋπολογισμού οικονομικού έτους 2025 για την εκτέλεση της πράξης «Βελτίωση και συντήρηση δρόμων Μελιδοχωρίου»',
        issueDate: '2025-10-13',
      },
      {
        ada: '977ΙΩΨΜ-Β7Ω',
        subject: 'Βελτίωση και συντήρηση δρόμων Μελιδοχωρίου (MIS 5221312)-Ανατροπή',
        issueDate: '2025-09-29',
      },
    ], { mode: 'modification', fromDate: '2025-08-08' });
    expect(ranked.map((r) => r.ada)).toEqual(['Ψ1ΘΟΩΨΜ-ΧΨΓ', 'ΨΓ25ΩΨΜ-ΘΓ4']);
    expect(ranked[0].role).toBe('council_budget');
    expect(ranked[1].role).toBe('committee_accept');
  });

  it('στον πρώτο έλεγχο ένταξης δεν κρατά «αποδοχή τροποποίησης»', () => {
    const ranked = match.rankAcceptanceCandidates({
      subject: 'Ένταξη της Πράξης «ΒΕΛΤΙΩΣΗ ΚΑΙ ΣΥΝΤΗΡΗΣΗ ΔΡΟΜΩΝ ΜΕΛΙΔΟΧΩΡΙΟΥ» με Κωδικό ΟΠΣ 5221312',
      opsCode: '5221312',
      documentDate: '2024-01-25',
    }, [{
      ada: 'ΨΓ25ΩΨΜ-ΘΓ4',
      subject: 'Απόφαση Δημοτικής Επιτροπής (299/2025): "Αποδοχή τροποποίησης πράξης: «βελτίωση και συντήρηση δρόμων Μελιδοχωρίου»"',
      issueDate: '2025-10-07',
    }]);
    expect(ranked).toEqual([]);
  });

  it('σε έλεγχο τροποποίησης απορρίπτει απόφαση πριν την ημερομηνία τροποποίησης', () => {
    const ranked = match.rankAcceptanceCandidates({
      subject: 'Ένταξη της Πράξης «ΑΝΑΠΛΑΣΗ ΓΕΦΥΡΑΣ» με Κωδικό ΟΠΣ 5225302',
      opsCode: '5225302',
      documentDate: '2024-11-28',
    }, [{
      ada: '9ΗΡΙΩΨΜ-Σ6Κ',
      subject: 'Αποδοχή χρηματοδότησης για την ένταξη της πράξης με τίτλο: ανάπλαση γέφυρας (με κωδικό ΟΠΣ 5225302)',
      issueDate: '2025-01-10',
    }], { mode: 'modification', fromDate: '2025-02-15' });
    expect(ranked).toEqual([]);
  });

  it('κρατά αποδοχή μεταβολής πρόσθετης χρηματοδότησης', () => {
    const ranked = match.rankAcceptanceCandidates({
      subject: 'Ένταξη της Πράξης «ΔΙΑΜΟΡΦΩΣΗ ΠΕΡΙΒΑΛΛΟΝΤΑ ΧΩΡΟΥ» με Κωδικό ΟΠΣ 5217517',
      opsCode: '5217517',
      documentDate: '2023-07-07',
    }, [{
      ada: 'Ψ1ΤΦΩΨΜ-6Η0',
      subject: 'Απόφαση Δημοτικής Επιτροπής (157/2025): "Αποδοχή μεταβολής (πρόσθετης) χρηματοδότησης για το έργο: διαμόρφωση περιβάλλοντα χώρου"',
      issueDate: '2025-06-10',
    }], { mode: 'modification', fromDate: '2025-05-30' });
    expect(ranked).toHaveLength(1);
    expect(ranked[0].role).toBe('committee_accept');
  });
});
