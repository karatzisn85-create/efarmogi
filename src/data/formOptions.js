export const MIN_STATUS_FOR_ASSIGNMENT_PROCEDURE = PROJECT_STATUS_CONTRACT_PROCESS;

/** ΑΔΑΜ προκήρυξης/διαγωνισμού — από «ΣΕ ΔΙΑΔΙΚΑΣΙΑ ΣΥΝΑΨΗΣ ΣΥΜΒΑΣΗΣ» και μετά */
export function statusAllowsKhmdhsNoticeInput(status) {
  return statusShowsAssignmentProcedure(status);
}

export function statusShowsAssignmentProcedure(status) {
  if (!status || isAbandonedSubproject(status)) return false;
  return PROJECT_STATUSES.indexOf(status) >= PROJECT_STATUSES.indexOf(MIN_STATUS_FOR_ASSIGNMENT_PROCEDURE);
}

/** Καταστάσεις με υπογεγραμμένη σύμβαση — ΑΔΑΜ ΚΗΜΔΗΣ + στοιχεία σύμβασης στη φόρμα */
export const STATUSES_WITH_KHMDHS_ADAM = [
  'ΕΚΤΕΛΟΥΜΕΝΟ - ΣΥΜΒΑΣΙΟΠΟΙΗΜΕΝΟ',
  'ΟΛΟΚΛΗΡΩΜΕΝΟ',
  'ΟΛΟΚΛΗΡΩΜΕΝΟ ΚΑΙ ΑΠΟΠΛΗΡΩΜΕΝΟ'
];

/** Καταστάσεις όπου η ανάκτηση ΚΗΜΔΗΣ δεν αλλάζει ποτέ αυτόματα την κατάσταση υποέργου */
export const KHMDHS_PROTECTED_PROJECT_STATUSES = [
  'ΟΛΟΚΛΗΡΩΜΕΝΟ',
  'ΟΛΟΚΛΗΡΩΜΕΝΟ ΚΑΙ ΑΠΟΠΛΗΡΩΜΕΝΟ',
];

export function isKhmdhsStatusProtectedFromAutoUpdate(status) {
  return KHMDHS_PROTECTED_PROJECT_STATUSES.includes(status);
}

/** Κατάσταση «Ολοκληρωμένο» ή μεταγενέστερη (π.χ. αποπληρωμένο) — όχι πρόταση ολοκλήρωσης. */
export function isProjectStatusAtOrBeyondCompleted(status) {
  if (!status || status === PROJECT_STATUS_ABANDONED) return false;
  if (isKhmdhsStatusProtectedFromAutoUpdate(status)) return true;
  const completedIdx = PROJECT_STATUSES.indexOf('ΟΛΟΚΛΗΡΩΜΕΝΟ');
  const idx = PROJECT_STATUSES.indexOf(status);
  return idx >= 0 && completedIdx >= 0 && idx >= completedIdx;
}

export const STATUSES_WITH_CONTRACT_FIELDS = STATUSES_WITH_KHMDHS_ADAM;

// Ο χαρακτηρισμός ΝΕΟ/ΣΥΝΕΧΙΖΟΜΕΝΟ δεν ισχύει για αυτές τις καταστάσεις
export const STATUS_NO_CHARACTERIZATION = 'ΟΛΟΚΛΗΡΩΜΕΝΟ ΚΑΙ ΑΠΟΠΛΗΡΩΜΕΝΟ';
export const STATUSES_WITHOUT_CHARACTERIZATION = [
  STATUS_NO_CHARACTERIZATION,
  PROJECT_STATUS_ABANDONED
];

/** Κλειστός κύκλος ΚΗΜΔΗΣ — δεν εφαρμόζεται ανανέωση αλυσίδας */
export function isKhmdhsChainClosedSubproject(projectOrStatus) {
  const status = typeof projectOrStatus === 'string'
    ? projectOrStatus
    : projectOrStatus?.projectStatus;
  return status === STATUS_NO_CHARACTERIZATION;
}

/**
 * Υπολογίζει τον χαρακτηρισμό ενός υποέργου: 'ΝΕΟ', 'ΣΥΝΕΧΙΖΟΜΕΝΟ', ή null.
 * - null: το υποέργο είναι "ΟΛΟΚΛΗΡΩΜΕΝΟ ΚΑΙ ΑΠΟΠΛΗΡΩΜΕΝΟ" → δεν εμφανίζεται χαρακτηρισμός
 * - 'ΣΥΝΕΧΙΖΟΜΕΝΟ': η σύμβαση υπογράφηκε σε ΠΡΟΗΓΟΥΜΕΝΟ έτος
 * - 'ΝΕΟ': δεν υπάρχει σύμβαση, ή η σύμβαση είναι εντός του τρέχοντος ή μελλοντικού έτους
 */
export const getCharacterization = (project) => {
  if (!project) return null;
  if (STATUSES_WITHOUT_CHARACTERIZATION.includes(project.projectStatus)) return null;

  const currentYear = new Date().getFullYear();

  // Συλλέγουμε όλες τις ημερομηνίες συμβάσεων
  const contractDates = [];
  if (project.contractDate) {
    contractDates.push(project.contractDate);
  }
  if (project.contracts && Array.isArray(project.contracts)) {
    project.contracts.forEach(c => { if (c.date) contractDates.push(c.date); });
  }

  if (contractDates.length === 0) return 'ΝΕΟ';

  // Αρκεί μία σύμβαση σε προηγούμενο έτος για να θεωρηθεί ΣΥΝΕΧΙΖΟΜΕΝΟ
  const hasOlderContract = contractDates.some(d => {
    try { return new Date(d).getFullYear() < currentYear; } catch { return false; }
  });

  return hasOlderContract ? 'ΣΥΝΕΧΙΖΟΜΕΝΟ' : 'ΝΕΟ';
};
